CREATE TABLE IF NOT EXISTS public.benchmark_runs (
    benchmark_run_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scenario VARCHAR(200) NOT NULL,
    endpoint TEXT NOT NULL,
    executed_at TIMESTAMPTZ NOT NULL,
    dataset_size BIGINT NOT NULL,
    min_duration_ms DOUBLE PRECISION NOT NULL,
    max_duration_ms DOUBLE PRECISION NOT NULL,
    average_duration_ms DOUBLE PRECISION NOT NULL,
    median_duration_ms DOUBLE PRECISION NOT NULL,
