CREATE TABLE IF NOT EXISTS public.query_history (
    query_history_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    executed_at TIMESTAMPTZ NOT NULL,
    entity_set VARCHAR(40) NOT NULL,
    request_url VARCHAR(2048) NOT NULL,
    duration_ms DOUBLE PRECISION NOT NULL CHECK (duration_ms >= 0),
    payload_bytes BIGINT NOT NULL CHECK (payload_bytes >= 0),
    http_status_code INTEGER NOT NULL CHECK (http_status_code BETWEEN 0 AND 599),
    result_count INTEGER NOT NULL CHECK (result_count >= 0),
    error_message VARCHAR(2000)
);

CREATE INDEX IF NOT EXISTS ix_query_history_executed_at ON public.query_history(executed_at DESC);
