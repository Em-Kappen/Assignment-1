        ALTER TABLE public.employees ADD CONSTRAINT fk_employees_manager
            FOREIGN KEY (manager_id) REFERENCES public.employees(employee_id) ON DELETE RESTRICT;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_employees_branch') THEN
        ALTER TABLE public.employees ADD CONSTRAINT fk_employees_branch
            FOREIGN KEY (branch_id) REFERENCES public.branches(branch_id) ON DELETE RESTRICT;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_products_branch') THEN
