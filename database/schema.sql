CREATE TABLE IF NOT EXISTS public.customers (
    customer_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_number VARCHAR(32) NOT NULL UNIQUE,
    first_name VARCHAR(80) NOT NULL,
    last_name VARCHAR(80) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE,
    phone VARCHAR(32) NOT NULL,
    address_line1 VARCHAR(160) NOT NULL,
    city VARCHAR(100) NOT NULL,
    state VARCHAR(100) NOT NULL,
    country VARCHAR(80) NOT NULL,
    created_date TIMESTAMP NOT NULL,
    is_active BOOLEAN NOT NULL
);

CREATE TABLE IF NOT EXISTS public.products (
    product_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku VARCHAR(40) NOT NULL,
    product_name VARCHAR(160) NOT NULL,
    category VARCHAR(80) NOT NULL,
    description VARCHAR(500) NOT NULL,
    unit_price NUMERIC(12,2) NOT NULL CHECK (unit_price >= 0),
    stock_quantity INTEGER NOT NULL CHECK (stock_quantity >= 0),
    created_date TIMESTAMP NOT NULL,
    is_active BOOLEAN NOT NULL,
    branch_id INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS public.orders (
    order_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INTEGER NOT NULL REFERENCES public.customers(customer_id) ON DELETE RESTRICT,
    order_number VARCHAR(40) NOT NULL UNIQUE,
    order_date TIMESTAMP NOT NULL,
    order_status VARCHAR(24) NOT NULL,
    subtotal NUMERIC(14,2) NOT NULL CHECK (subtotal >= 0),
    tax_amount NUMERIC(14,2) NOT NULL CHECK (tax_amount >= 0),
    shipping_amount NUMERIC(14,2) NOT NULL CHECK (shipping_amount >= 0),
    total_amount NUMERIC(14,2) NOT NULL CHECK (total_amount = subtotal + tax_amount + shipping_amount)
);

CREATE TABLE IF NOT EXISTS public.order_items (
    order_item_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id INTEGER NOT NULL REFERENCES public.orders(order_id) ON DELETE CASCADE,
    product_id INTEGER NOT NULL REFERENCES public.products(product_id) ON DELETE RESTRICT,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(12,2) NOT NULL CHECK (unit_price >= 0),
    line_total NUMERIC(14,2) NOT NULL CHECK (line_total = quantity * unit_price)
);

